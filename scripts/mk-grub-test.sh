#!/bin/sh
# mk-grub-test.sh - a disk with a "host Linux" GRUB that boots the Atari
# through scripts/install-linux.sh's custom.cfg (run inside the Alpine env)
#
#   scripts/alpine-env.sh run apk add grub grub-bios e2fsprogs     (once)
#   scripts/alpine-env.sh run scripts/mk-grub-test.sh partition|image
#   QEMU_IMG=build/grub-test.img QEMU_IMG_AS=ide scripts/qemu-test.sh start bios
#
# build/grub-test.img (sparse, MBR): partition 1 is an ext4 "Linux root"
# with BIOS GRUB (boot.img in the MBR, core.img in the gap, modules and a
# grub.cfg in /boot/grub like grub-install leaves them), partition 2 an
# empty-looking FAT32 that holds the files zip's content. The grub.cfg has
# a dummy Linux entry, the distro's 41_custom block and the load_env /
# next_entry logic of 00_header; grubenv says next_entry=atari-os, i.e.
# what "grub-reboot atari-os" does. custom.cfg is exactly what
# install-linux.sh writes (its entry functions, sourced), for:
#   partition   the FAT32 partition 2 (atari.media=<its serial>)
#   image       build/atari-os.img as /atari/atari-os-x86.img on partition 1
#               (loopback, atari.image=<ext4 UUID>:/atari/atari-os-x86.img)
# GRUB_EFI=1 also puts an x86_64-efi GRUB (same prefix, same grub.cfg) on
# partition 2 as \EFI\BOOT\BOOTX64.EFI (instead of Limine's in partition
# mode), for "scripts/qemu-test.sh start uefi" (apk add grub-efi).
# The kernel command line gets console=ttyS0,115200 atari.debug=1 for the
# serial shell. Only ever writes build/grub-test.img and build/grub-test/.

set -eu
PROJECT="$(cd "$(dirname "$0")/.." && pwd)"
[ -f /etc/alpine-release ] || { echo "error: run me through scripts/alpine-env.sh run $0" >&2; exit 1; }
TEST_MODE="${1:-partition}"
case "$TEST_MODE" in partition|image) ;; *) echo "usage: $0 partition|image" >&2; exit 1 ;; esac
BUILD=$PROJECT/build
OUT=$BUILD/grub-test.img
W=$BUILD/grub-test
GRUBLIB=/usr/lib/grub/i386-pc
ZIP=''
for z in "$BUILD"/atari-os-x86-*-files.zip; do [ -f "$z" ] && ZIP=$z && break; done
for t in grub-mkimage grub-editenv mkfs.ext4 mkfs.vfat mcopy sfdisk unzip; do
	command -v "$t" >/dev/null || { echo "missing $t: apk add grub grub-bios e2fsprogs" >&2; exit 1; }
done
[ -f "$GRUBLIB/boot.img" ] || { echo "no $GRUBLIB (apk add grub-bios)" >&2; exit 1; }
[ -n "$ZIP" ] || { echo "no build/atari-os-x86-*-files.zip (scripts/mkimage.sh)" >&2; exit 1; }
EXT_UUID=6a7a1000-0000-4000-8000-00000000c0de
FAT_ID=1A2B3C4D
FAT_SERIAL=1A2B-3C4D
P1_MB=1600 P2_MB=1600

rm -rf "$W" "$OUT"
mkdir -p "$W/root/boot/grub/i386-pc" "$W/root/etc/default" "$W/files"
cp "$GRUBLIB"/*.mod "$GRUBLIB"/*.lst "$W/root/boot/grub/i386-pc/"
if [ "${GRUB_EFI:-0}" = 1 ]; then
	[ -d /usr/lib/grub/x86_64-efi ] || { echo "no /usr/lib/grub/x86_64-efi (apk add grub-efi)" >&2; exit 1; }
	mkdir -p "$W/root/boot/grub/x86_64-efi" "$W/efi/EFI/BOOT"
	cp /usr/lib/grub/x86_64-efi/*.mod /usr/lib/grub/x86_64-efi/*.lst "$W/root/boot/grub/x86_64-efi/"
	grub-mkimage -O x86_64-efi -o "$W/efi/EFI/BOOT/BOOTX64.EFI" -p '(hd0,msdos1)/boot/grub' part_msdos ext2 fat
fi

# grub.cfg as grub-mkconfig would write it (the parts that matter here)
cat > "$W/root/boot/grub/grub.cfg" <<'CFG'
# generated by mk-grub-test.sh in the shape of grub-mkconfig's output
### BEGIN /etc/grub.d/00_header ###
if [ -s $prefix/grubenv ]; then
  load_env
fi
if [ "${next_entry}" ] ; then
   set default="${next_entry}"
   set next_entry=
   save_env next_entry
else
   set default="0"
fi
serial --unit=0 --speed=115200
terminal_input console serial
terminal_output console serial
set timeout=3
### END /etc/grub.d/00_header ###
### BEGIN /etc/grub.d/10_linux ###
menuentry 'Some Linux (dummy)' --id some-linux {
	echo 'this would be the host Linux'
	sleep 5
}
### END /etc/grub.d/10_linux ###
### BEGIN /etc/grub.d/41_custom ###
if [ -f  ${config_directory}/custom.cfg ]; then
  source ${config_directory}/custom.cfg
elif [ -z "${config_directory}" -a -f  $prefix/custom.cfg ]; then
  source $prefix/custom.cfg
fi
### END /etc/grub.d/41_custom ###
CFG
grub-editenv "$W/root/boot/grub/grubenv" set next_entry=atari-os
printf 'GRUB_DEFAULT=saved\n' > "$W/root/etc/default/grub"

# custom.cfg from install-linux.sh's own functions
CMDLINE="$(unzip -p "$ZIP" limine.conf | sed -n 's/^[[:space:]]*cmdline:[[:space:]]*//p' | head -n 1) console=ttyS0,115200 atari.debug=1"
export INSTALL_LINUX_LIB=1
set -- --check
# shellcheck source=/dev/null
. "$PROJECT/scripts/install-linux.sh"
set +e
if [ "$TEST_MODE" = partition ]; then
	grub_entry_partition "$FAT_SERIAL" "$CMDLINE" | custom_cfg_text "partition /dev/sda2 (FAT32 serial $FAT_SERIAL)"
else
	mkdir -p "$W/root/atari"
	cp --sparse=always "$BUILD/atari-os.img" "$W/root/atari/atari-os-x86.img" 2>/dev/null \
		|| cp "$BUILD/atari-os.img" "$W/root/atari/atari-os-x86.img"
	grub_entry_image ext2 "$EXT_UUID" /atari/atari-os-x86.img "$CMDLINE" | custom_cfg_text "image /atari/atari-os-x86.img"
fi > "$W/root/boot/grub/custom.cfg"
set -e
echo "custom.cfg:"; cat "$W/root/boot/grub/custom.cfg"

# the disk: MBR with both partitions, the filesystems made in place
truncate -s $(( (2 + P1_MB + P2_MB) * 1024 * 1024 )) "$OUT"
printf 'label: dos\nstart=2048, size=%s, type=83, bootable\nsize=%s, type=c\n' \
	$((P1_MB * 2048)) $((P2_MB * 2048)) | sfdisk -q "$OUT"
P2_SECT=$(( (1 + P1_MB) * 2048 ))
# partition 1: ext4 with /boot/grub (and the image in loopback mode)
mkfs.ext4 -q -F -L linuxroot -U "$EXT_UUID" -E offset=1048576 -d "$W/root" "$OUT" "${P1_MB}M"
# partition 2: FAT32 with the zip's files (partition mode) or empty
mkfs.vfat -F 32 -n ATARI -s 8 -i "$FAT_ID" --offset "$P2_SECT" -h "$P2_SECT" "$OUT" $((P2_MB * 1024)) >/dev/null
if [ "$TEST_MODE" = partition ]; then
	(cd "$W/files" && unzip -q "$ZIP")
	sed -i "/^[[:space:]]*cmdline:/s/\$/ atari.media=$FAT_SERIAL/" "$W/files/limine.conf"
	MTOOLS_SKIP_CHECK=1 mcopy -i "$OUT@@$((P2_SECT * 512))" -s -Q "$W/files"/* ::
fi
if [ "${GRUB_EFI:-0}" = 1 ]; then
	MTOOLS_SKIP_CHECK=1 mcopy -o -i "$OUT@@$((P2_SECT * 512))" -s -Q "$W/efi/EFI" ::
fi
# GRUB: boot.img in the MBR (before the partition table), core.img in the gap
grub-mkimage -O i386-pc -o "$W/core.img" -p '(hd0,msdos1)/boot/grub' biosdisk part_msdos ext2
[ "$(stat -c %s "$W/core.img")" -lt $((2047 * 512)) ] || { echo "core.img too big for the gap" >&2; exit 1; }
dd if="$GRUBLIB/boot.img" of="$OUT" bs=440 count=1 conv=notrunc status=none
dd if="$W/core.img" of="$OUT" bs=512 seek=1 conv=notrunc status=none
rm -rf "$W/files" "$W/root/atari" "$W/efi"
ls -lsh "$OUT"
echo "$TEST_MODE mode; boot: QEMU_IMG=build/grub-test.img QEMU_IMG_AS=ide scripts/qemu-test.sh start bios"
